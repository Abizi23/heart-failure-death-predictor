
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import ssl
import os

# Serve the taskpane source files directly (no webpack build needed)
REPO_ROOT    = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TASKPANE_DIR = os.path.join(REPO_ROOT, "gantt-outlook-addin", "src", "taskpane")
ADDIN_DIR    = os.path.join(REPO_ROOT, "gantt-outlook-addin")


class GanttHandler(SimpleHTTPRequestHandler):
    """Serve taskpane files; fall back to addin root for assets."""

    def translate_path(self, path):
        # Strip query string
        path = path.split("?", 1)[0].split("#", 1)[0]

        # Map /assets/* → gantt-outlook-addin/assets/
        if path.startswith("/assets/"):
            rel = path.lstrip("/")
            return os.path.join(ADDIN_DIR, rel)

        # Map /taskpane.html → src/taskpane/taskpane.html
        if path in ("/", "/taskpane.html", "/taskpane"):
            return os.path.join(TASKPANE_DIR, "taskpane.html")

        # Map /commands.html → src/commands/commands.html
        if path in ("/commands.html", "/commands"):
            return os.path.join(ADDIN_DIR, "src", "commands", "commands.html")

        # Everything else: look in taskpane dir first, then addin root
        rel = path.lstrip("/")
        candidate = os.path.join(TASKPANE_DIR, rel)
        if os.path.exists(candidate):
            return candidate
        return os.path.join(ADDIN_DIR, rel)

    def log_message(self, fmt, *args):
        print(f"[{self.address_string()}] {fmt % args}")


server = ThreadingHTTPServer(("localhost", 3000), GanttHandler)

# Use project-local certs generated by generate_certs.py
CERT_DIR = os.path.join(REPO_ROOT, "certs")

context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
context.load_cert_chain(
    os.path.join(CERT_DIR, "localhost.crt"),
    os.path.join(CERT_DIR, "localhost.key"),
)

server.socket = context.wrap_socket(server.socket, server_side=True)

print("Task pane server running:")
print("  Task pane : https://localhost:3000/taskpane.html")
print("  Commands  : https://localhost:3000/commands.html")
print("  Serving   :", TASKPANE_DIR)
print()

server.serve_forever()
